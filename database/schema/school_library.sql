-- Carbonell School Library schema for Supabase PostgreSQL.
-- Paste into Supabase SQL Editor for a new project. Uses the public schema.

CREATE TABLE IF NOT EXISTS roles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(32) NOT NULL UNIQUE,
  name VARCHAR(80) NOT NULL,
  description VARCHAR(255),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(80) NOT NULL UNIQUE,
  email VARCHAR(254) UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  first_name VARCHAR(100) NOT NULL,
  last_name VARCHAR(100) NOT NULL,
  account_status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' CHECK (account_status IN ('ACTIVE','DISABLED','LOCKED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_users_name ON users (last_name, first_name);
CREATE INDEX IF NOT EXISTS ix_users_status ON users (account_status);

CREATE TABLE IF NOT EXISTS user_roles (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
  assigned_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, role_id)
);
CREATE INDEX IF NOT EXISTS ix_user_roles_role ON user_roles (role_id, user_id);

CREATE TABLE IF NOT EXISTS student_profiles (
  user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  student_number VARCHAR(40) NOT NULL UNIQUE,
  program VARCHAR(120),
  year_level VARCHAR(20),
  section VARCHAR(50),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_student_profiles_program_year_section ON student_profiles (program, year_level, section);

CREATE TABLE IF NOT EXISTS loan_policies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  borrower_role_id BIGINT NOT NULL UNIQUE REFERENCES roles(id) ON DELETE RESTRICT,
  loan_period_days SMALLINT NOT NULL CHECK (loan_period_days > 0),
  max_active_loans SMALLINT NOT NULL CHECK (max_active_loans > 0),
  max_renewals SMALLINT NOT NULL DEFAULT 0 CHECK (max_renewals >= 0),
  renewal_extension_days SMALLINT NOT NULL DEFAULT 0 CHECK (renewal_extension_days >= 0),
  max_active_reservations SMALLINT NOT NULL DEFAULT 0 CHECK (max_active_reservations >= 0),
  is_active SMALLINT NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS publishers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(180) NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS authors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  display_name VARCHAR(180) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_authors_display_name ON authors (display_name);
CREATE TABLE IF NOT EXISTS categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_category_id BIGINT REFERENCES categories(id) ON DELETE SET NULL,
  name VARCHAR(120) NOT NULL UNIQUE,
  description VARCHAR(500),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_categories_parent ON categories (parent_category_id);

CREATE TABLE IF NOT EXISTS books (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  isbn VARCHAR(20) UNIQUE,
  title VARCHAR(255) NOT NULL,
  subtitle VARCHAR(255),
  edition VARCHAR(80),
  publication_year SMALLINT CHECK (publication_year IS NULL OR publication_year BETWEEN 1000 AND 9999),
  language_code VARCHAR(10),
  publisher_id BIGINT REFERENCES publishers(id) ON DELETE SET NULL,
  description TEXT,
  cover_image_url VARCHAR(255),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_books_title ON books (title);
CREATE INDEX IF NOT EXISTS ix_books_publisher ON books (publisher_id);

CREATE TABLE IF NOT EXISTS book_authors (
  book_id BIGINT NOT NULL REFERENCES books(id) ON DELETE CASCADE,
  author_id BIGINT NOT NULL REFERENCES authors(id) ON DELETE RESTRICT,
  author_order SMALLINT NOT NULL DEFAULT 1 CHECK (author_order > 0),
  PRIMARY KEY (book_id, author_id),
  UNIQUE (book_id, author_order)
);
CREATE INDEX IF NOT EXISTS ix_book_authors_author ON book_authors (author_id, book_id);
CREATE TABLE IF NOT EXISTS book_categories (
  book_id BIGINT NOT NULL REFERENCES books(id) ON DELETE CASCADE,
  category_id BIGINT NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
  PRIMARY KEY (book_id, category_id)
);
CREATE INDEX IF NOT EXISTS ix_book_categories_category ON book_categories (category_id, book_id);

CREATE TABLE IF NOT EXISTS book_copies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id BIGINT NOT NULL REFERENCES books(id) ON DELETE RESTRICT,
  barcode VARCHAR(80) NOT NULL UNIQUE,
  copy_status VARCHAR(16) NOT NULL DEFAULT 'IN_SERVICE' CHECK (copy_status IN ('IN_SERVICE','DAMAGED','LOST','WITHDRAWN')),
  shelf_location VARCHAR(100),
  acquired_at DATE,
  notes VARCHAR(1000),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (id, book_id)
);
CREATE INDEX IF NOT EXISTS ix_book_copies_book_status ON book_copies (book_id, copy_status);

CREATE TABLE IF NOT EXISTS reservations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book_id BIGINT NOT NULL REFERENCES books(id) ON DELETE RESTRICT,
  student_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  allocated_copy_id BIGINT,
  status VARCHAR(16) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','READY','FULFILLED','CANCELLED','EXPIRED')),
  requested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  ready_at TIMESTAMPTZ,
  expires_at TIMESTAMPTZ,
  closed_at TIMESTAMPTZ,
  UNIQUE (id, student_user_id),
  FOREIGN KEY (allocated_copy_id, book_id) REFERENCES book_copies(id, book_id) ON DELETE RESTRICT,
  CHECK (
    (status = 'PENDING' AND allocated_copy_id IS NULL AND ready_at IS NULL AND expires_at IS NULL AND closed_at IS NULL)
    OR (status = 'READY' AND allocated_copy_id IS NOT NULL AND ready_at IS NOT NULL AND expires_at > ready_at AND closed_at IS NULL)
    OR (status IN ('FULFILLED','CANCELLED','EXPIRED') AND allocated_copy_id IS NULL AND closed_at IS NOT NULL)
  )
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_reservations_active_student_book ON reservations (student_user_id, book_id) WHERE status IN ('PENDING','READY');
CREATE UNIQUE INDEX IF NOT EXISTS uq_reservations_ready_copy ON reservations (allocated_copy_id) WHERE status = 'READY';
CREATE INDEX IF NOT EXISTS ix_reservations_queue ON reservations (book_id, status, requested_at, id);
CREATE INDEX IF NOT EXISTS ix_reservations_student_status ON reservations (student_user_id, status);

CREATE TABLE IF NOT EXISTS loans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  copy_id BIGINT NOT NULL REFERENCES book_copies(id) ON DELETE RESTRICT,
  borrower_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  reservation_id BIGINT UNIQUE,
  checked_out_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  checked_out_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  due_at TIMESTAMPTZ NOT NULL,
  status VARCHAR(12) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','RETURNED','LOST')),
  returned_at TIMESTAMPTZ,
  returned_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  return_condition VARCHAR(8) CHECK (return_condition IS NULL OR return_condition IN ('GOOD','DAMAGED')),
  return_notes VARCHAR(1000),
  lost_at TIMESTAMPTZ,
  return_requested_at TIMESTAMPTZ,
  return_requested_note VARCHAR(500),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  FOREIGN KEY (reservation_id, borrower_user_id) REFERENCES reservations(id, student_user_id) ON DELETE RESTRICT,
  CHECK (due_at > checked_out_at),
  CHECK (
    (status = 'ACTIVE' AND returned_at IS NULL AND lost_at IS NULL AND return_condition IS NULL)
    OR (status = 'RETURNED' AND returned_at >= checked_out_at AND lost_at IS NULL AND return_condition IS NOT NULL)
    OR (status = 'LOST' AND lost_at >= checked_out_at AND returned_at IS NULL AND return_condition IS NULL)
  )
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_loans_active_copy ON loans (copy_id) WHERE status = 'ACTIVE';
CREATE INDEX IF NOT EXISTS ix_loans_borrower_status ON loans (borrower_user_id, status, due_at);
CREATE INDEX IF NOT EXISTS ix_loans_status_due ON loans (status, due_at);
CREATE INDEX IF NOT EXISTS ix_loans_copy_history ON loans (copy_id, checked_out_at);
CREATE INDEX IF NOT EXISTS ix_loans_checkout_staff ON loans (checked_out_by_user_id);
CREATE INDEX IF NOT EXISTS ix_loans_return_staff ON loans (returned_by_user_id);

CREATE TABLE IF NOT EXISTS borrowing_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  book_id BIGINT NOT NULL REFERENCES books(id) ON DELETE RESTRICT,
  status VARCHAR(12) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','REJECTED','ISSUED')),
  student_note VARCHAR(500),
  response_reason VARCHAR(500),
  handled_by_user_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
  issued_by_user_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
  loan_id BIGINT UNIQUE REFERENCES loans(id) ON DELETE RESTRICT,
  requested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  resolved_at TIMESTAMPTZ,
  issued_at TIMESTAMPTZ,
  CHECK (
    (status = 'PENDING' AND resolved_at IS NULL AND handled_by_user_id IS NULL AND issued_by_user_id IS NULL AND loan_id IS NULL AND issued_at IS NULL AND response_reason IS NULL)
    OR (status = 'APPROVED' AND resolved_at IS NOT NULL AND handled_by_user_id IS NOT NULL AND issued_by_user_id IS NULL AND loan_id IS NULL AND issued_at IS NULL AND response_reason IS NULL)
    OR (status = 'REJECTED' AND resolved_at IS NOT NULL AND handled_by_user_id IS NOT NULL AND issued_by_user_id IS NULL AND loan_id IS NULL AND issued_at IS NULL AND response_reason IS NOT NULL)
    OR (status = 'ISSUED' AND resolved_at IS NOT NULL AND handled_by_user_id IS NOT NULL AND issued_by_user_id IS NOT NULL AND loan_id IS NOT NULL AND issued_at IS NOT NULL AND response_reason IS NULL)
  )
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_borrowing_requests_pending_student_book ON borrowing_requests (student_user_id, book_id) WHERE status = 'PENDING';
CREATE INDEX IF NOT EXISTS ix_borrowing_requests_status_requested ON borrowing_requests (status, requested_at, id);
CREATE INDEX IF NOT EXISTS ix_borrowing_requests_student ON borrowing_requests (student_user_id, requested_at);
CREATE INDEX IF NOT EXISTS ix_borrowing_requests_issuer ON borrowing_requests (issued_by_user_id);

CREATE TABLE IF NOT EXISTS renewals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  loan_id BIGINT NOT NULL REFERENCES loans(id) ON DELETE RESTRICT,
  renewal_number SMALLINT NOT NULL CHECK (renewal_number > 0),
  renewed_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  renewed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  old_due_at TIMESTAMPTZ NOT NULL,
  new_due_at TIMESTAMPTZ NOT NULL CHECK (new_due_at > old_due_at),
  notes VARCHAR(500),
  UNIQUE (loan_id, renewal_number)
);
CREATE INDEX IF NOT EXISTS ix_renewals_actor ON renewals (renewed_by_user_id);

CREATE TABLE IF NOT EXISTS notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  notification_type VARCHAR(40) NOT NULL,
  title VARCHAR(180) NOT NULL,
  body TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  read_at TIMESTAMPTZ,
  dedupe_key VARCHAR(100),
  UNIQUE (user_id, dedupe_key)
);
CREATE INDEX IF NOT EXISTS ix_notifications_user_created ON notifications (user_id, created_at);
CREATE INDEX IF NOT EXISTS ix_notifications_user_read ON notifications (user_id, read_at);

CREATE TABLE IF NOT EXISTS audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  action VARCHAR(60) NOT NULL,
  entity_type VARCHAR(60) NOT NULL,
  entity_id BIGINT,
  old_values JSONB,
  new_values JSONB,
  ip_address VARCHAR(45),
  user_agent VARCHAR(500),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_audit_actor_created ON audit_logs (actor_user_id, created_at);
CREATE INDEX IF NOT EXISTS ix_audit_entity_created ON audit_logs (entity_type, entity_id, created_at);

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DO $$
DECLARE table_name TEXT;
BEGIN
  FOREACH table_name IN ARRAY ARRAY['users','student_profiles','loan_policies','books','book_copies'] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS set_updated_at ON public.%I', table_name);
    EXECUTE format('CREATE TRIGGER set_updated_at BEFORE UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.set_updated_at()', table_name);
  END LOOP;
END;
$$;

